#!/usr/bin/env python3
"""Regenerates Resources/vi.lproj/Localizable.strings from vi_translations.py and reports missing keys."""
import os, subprocess, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from vi_translations import VI

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
keys = subprocess.run([sys.executable, os.path.join(ROOT, "scripts", "extract_strings.py")],
                      capture_output=True, text=True, check=True).stdout.splitlines()
ignore = {"mdm.hls.timer", "mdm.bridge", "MacOS Download Manager", "–"}
keys = [k.replace('\\"', '"') for k in keys]
missing = [k for k in keys if k not in VI and k not in ignore]

lines = ["/* MacOS Download Manager – Vietnamese localization (generated by scripts/gen_strings.py) */", ""]
for k, v in VI.items():
    key = k.replace('"', '\\"')
    value = v.replace('"', '\\"')
    lines.append(f'"{key}" = "{value}";')
out = os.path.join(ROOT, "Resources", "vi.lproj", "Localizable.strings")
os.makedirs(os.path.dirname(out), exist_ok=True)
open(out, "w", encoding="utf-8").write("\n".join(lines) + "\n")

en = os.path.join(ROOT, "Resources", "en.lproj", "Localizable.strings")
os.makedirs(os.path.dirname(en), exist_ok=True)
open(en, "w", encoding="utf-8").write("/* English is the development language: keys are the English strings. */\n")

print(f"wrote {len(VI)} strings; missing translations: {len(missing)}")
for k in missing:
    print("  MISSING:", k)
